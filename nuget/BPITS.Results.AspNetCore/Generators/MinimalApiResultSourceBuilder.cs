using System.Text;
using BPITS.Results.Helpers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace BPITS.Results.AspNetCore.Generators;

// Kept apart from the controller generator so its IActionResult output stays byte-for-byte unchanged.
internal static class MinimalApiResultSourceBuilder
{
    public static void Execute(
        ApiResultGeneratorArguments generatorArgs,
        MinimalApiSupport support,
        SourceProductionContext context)
    {
        if (!support.CanImplementResult)
            return;

        var enumSymbol = generatorArgs.NamedTypeSymbol;

        // The controller generator already reports BPITSR001 for this; repeating it would duplicate the error.
        if (!enumSymbol.GetMembers().OfType<IFieldSymbol>().Any(f => f.Name == "Ok"))
            return;

        var enumNamespace = enumSymbol.ContainingNamespace.ToDisplayString();
        var enumName = enumSymbol.Name;

        var executorSource = GenerateExecutor(enumName, enumNamespace, GetDocumentedStatusCodes(enumSymbol));
        context.AddSource($"{enumName}HttpResultExecutor.g.cs", SourceText.From(executorSource, Encoding.UTF8));

        var partialsSource = GenerateApiResultPartials(enumName, enumNamespace, support.CanPopulateMetadata);
        context.AddSource($"ApiResult_{enumName}_IResult.g.cs", SourceText.From(partialsSource, Encoding.UTF8));
    }

    private static IReadOnlyList<int> GetDocumentedStatusCodes(INamedTypeSymbol enumSymbol)
    {
        var statusCodes = new SortedSet<int>();
        var hasUnmappedMember = false;

        foreach (var member in enumSymbol.GetMembers().OfType<IFieldSymbol>())
        {
            if (!member.IsStatic || !member.HasConstantValue)
                continue;

            var httpStatusAttribute = member.GetAttributes()
                .FirstOrDefault(attr => attr.AttributeClass?.Name == "HttpStatusCodeAttribute");

            if (httpStatusAttribute is { ConstructorArguments.Length: > 0 }
                && httpStatusAttribute.ConstructorArguments[0].Value is { } value)
            {
                statusCodes.Add(Convert.ToInt32(value));
            }
            else
            {
                hasUnmappedMember = true;
            }
        }

        // Members without [HttpStatusCode] fall through to the mapper's 200 default.
        if (hasUnmappedMember || statusCodes.Count == 0)
            statusCodes.Add(200);

        return statusCodes.ToList();
    }

    private static string GenerateExecutor(string enumName, string enumNamespace, IReadOnlyList<int> statusCodes)
    {
        var documentedStatusCodes = string.Join(", ", statusCodes);

        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace {{enumNamespace}}
            {
                [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
                internal static class {{enumName}}HttpResultExecutor
                {
                    private static readonly string[] JsonContentTypes = { "application/json" };

                    // Read at compile time, so a custom mapper registered at runtime can make OpenAPI disagree.
                    private static readonly int[] DocumentedStatusCodes = { {{documentedStatusCodes}} };

                    // Matches what ASP.NET Core's own IResult types use when JsonOptions isn't in the container.
                    private static readonly global::Microsoft.AspNetCore.Http.Json.JsonOptions DefaultJsonOptions =
                        new global::Microsoft.AspNetCore.Http.Json.JsonOptions();

                    public static global::System.Threading.Tasks.Task ExecuteAsync<TResult>(
                        global::Microsoft.AspNetCore.Http.HttpContext httpContext,
                        TResult result,
                        {{enumName}} statusCode)
                    {
                        if (httpContext is null)
                            throw new global::System.ArgumentNullException(nameof(httpContext));

                        var services = httpContext.RequestServices;

                        // Fail loudly: a silent fallback would ship wrong status codes to production.
                        var mapper = services.GetService(typeof(global::BPITS.Results.AspNetCore.Abstractions.IActionResultMapper<{{enumName}}>))
                            as global::BPITS.Results.AspNetCore.Abstractions.IActionResultMapper<{{enumName}}>
                            ?? throw new global::System.InvalidOperationException(
                                "No IActionResultMapper<{{enumName}}> is registered, so ApiResult cannot choose an HTTP status code. " +
                                "Call builder.Services.Add{{enumName}}ActionResultMapper() (or register your own IActionResultMapper<{{enumName}}>) during startup.");

                        // Minimal APIs read Http.Json.JsonOptions, not the MVC options the controller path uses.
                        var jsonOptions = services.GetService(typeof(global::Microsoft.Extensions.Options.IOptions<global::Microsoft.AspNetCore.Http.Json.JsonOptions>))
                            as global::Microsoft.Extensions.Options.IOptions<global::Microsoft.AspNetCore.Http.Json.JsonOptions>;
                        var serializerOptions = jsonOptions?.Value.SerializerOptions ?? DefaultJsonOptions.SerializerOptions;

                        // JsonTypeInfo keeps this path working for apps that trim or use source-generated JSON contexts.
                        var typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<TResult>)
                            serializerOptions.GetTypeInfo(typeof(TResult));

                        httpContext.Response.StatusCode = (int)mapper.MapStatusCode(statusCode);

                        return global::Microsoft.AspNetCore.Http.HttpResponseJsonExtensions.WriteAsJsonAsync(
                            httpContext.Response,
                            result,
                            typeInfo,
                            contentType: null,
                            cancellationToken: httpContext.RequestAborted);
                    }

                    public static void PopulateMetadata(
                        global::Microsoft.AspNetCore.Builder.EndpointBuilder builder,
                        global::System.Type responseType)
                    {
                        if (builder is null)
                            throw new global::System.ArgumentNullException(nameof(builder));

                        foreach (var statusCode in DocumentedStatusCodes)
                        {
                            builder.Metadata.Add(new global::Microsoft.AspNetCore.Http.ProducesResponseTypeMetadata(
                                statusCode, responseType, JsonContentTypes));
                        }
                    }
                }
            }
            """;
    }

    private static string GenerateApiResultPartials(string enumName, string enumNamespace, bool populateMetadata)
    {
        var executor = $"global::{enumNamespace}.{enumName}HttpResultExecutor";
        var metadataInterface = populateMetadata
            ? ", global::Microsoft.AspNetCore.Http.Metadata.IEndpointMetadataProvider"
            : string.Empty;

        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace BPITS.Results
            {
                public partial record ApiResult : global::Microsoft.AspNetCore.Http.IResult{{metadataInterface}}
                {
                    public global::System.Threading.Tasks.Task ExecuteAsync(global::Microsoft.AspNetCore.Http.HttpContext httpContext)
                        => {{executor}}.ExecuteAsync(httpContext, this, StatusCode);
            {{GeneratePopulateMetadata(executor, "ApiResultResponse<object>", populateMetadata)}}
                }

                public partial record ApiResult<T> : global::Microsoft.AspNetCore.Http.IResult{{metadataInterface}}
                {
                    public global::System.Threading.Tasks.Task ExecuteAsync(global::Microsoft.AspNetCore.Http.HttpContext httpContext)
                        => {{executor}}.ExecuteAsync(httpContext, this, StatusCode);
            {{GeneratePopulateMetadata(executor, "ApiResultResponse<T>", populateMetadata)}}
                }
            {{GenerateResponseSchema(enumName, enumNamespace, populateMetadata)}}
            }
            """;
    }

    private static string GenerateResponseSchema(string enumName, string enumNamespace, bool populateMetadata)
    {
        if (!populateMetadata)
            return string.Empty;

        return $$"""

                // ApiExplorer ignores IResult response types, so OpenAPI documents this mirror of ApiResult's body instead.
                [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
                public sealed record ApiResultResponse<T>(
                    global::{{enumNamespace}}.{{enumName}} StatusCode,
                    T? Value,
                    string? ErrorMessage = null,
                    global::System.Collections.Generic.Dictionary<string, string[]>? ErrorDetails = null
                );
            """;
    }

    private static string GeneratePopulateMetadata(string executor, string responseType, bool populateMetadata)
    {
        if (!populateMetadata)
            return string.Empty;

        return $$"""

                    public static void PopulateMetadata(
                        global::System.Reflection.MethodInfo method,
                        global::Microsoft.AspNetCore.Builder.EndpointBuilder builder)
                        => {{executor}}.PopulateMetadata(builder, typeof({{responseType}}));
            """;
    }
}
